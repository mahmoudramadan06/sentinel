"""Report generation: JSON and Markdown."""

from __future__ import annotations

import datetime
import json
from typing import Dict

from . import __version__
from .models import SEVERITY_ORDER, ScanResult
from .redact import sanitize_markdown as _md


def _metadata(result: ScanResult) -> Dict:
    return {
        "tool": "sentinel-triage",
        "version": __version__,
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "target": result.target,
        "files_scanned": result.files_scanned,
        "files_skipped": result.files_skipped,
        "duplicates_removed": result.duplicates_removed,
        "baseline_suppressed": result.baseline_suppressed,
        "warnings": list(result.warnings),
        "investigations_planner": result.investigations_planner,
        "investigations_run": len(result.investigations),
        "llm_provider": result.llm_provider,
        "llm_used": result.llm_used,
        "llm_is_mock": result.llm_is_mock,
    }


def to_json(result: ScanResult) -> str:
    findings = []
    for f in result.findings:
        d = f.to_dict()
        note = result.triage_notes.get(f.fingerprint())
        if note:
            d["triage_note"] = note
        inv = result.investigations.get(f.fingerprint())
        if inv:
            d["investigation"] = inv
        findings.append(d)
    doc = {
        "metadata": _metadata(result),
        "severity_counts": result.severity_counts(),
        "findings": findings,
    }
    if "_error" in result.triage_notes:
        doc["llm_fallback"] = result.triage_notes["_error"]
    return json.dumps(doc, indent=2)


def to_markdown(result: ScanResult) -> str:
    meta = _metadata(result)
    counts = result.severity_counts()
    lines = []
    lines.append("# Security Triage Report")
    lines.append("")
    lines.append(f"- Target: `{meta['target']}`")
    lines.append(f"- Generated: {meta['generated_at']} by sentinel-triage v{meta['version']}")
    lines.append(
        f"- Files scanned: {meta['files_scanned']} "
        f"(skipped: {meta['files_skipped']}, duplicates removed: {meta['duplicates_removed']})"
    )
    if result.llm_used:
        provider_desc = meta["llm_provider"] + (" (offline mock, not a real model)" if result.llm_is_mock else "")
        lines.append(f"- LLM triage: {provider_desc}")
    else:
        lines.append("- LLM triage: not used (deterministic ranking only)")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Severity | Count |")
    lines.append("| --- | --- |")
    for sev in reversed(SEVERITY_ORDER):
        if counts.get(sev):
            lines.append(f"| {sev} | {counts[sev]} |")
    lines.append("")
    lines.append("## Findings (ranked by risk score)")
    lines.append("")
    for i, f in enumerate(result.findings, start=1):
        lines.append(f"### {i}. {f.title}")
        lines.append("")
        lines.append(
            f"- **Severity:** {f.severity} | **Confidence:** {f.confidence} "
            f"| **Risk score:** {f.risk_score()}"
        )
        lines.append(f"- **Location:** `{f.file}:{f.line}`")
        if f.cwe:
            lines.append(f"- **CWE:** {f.cwe}")
        lines.append(f"- **Evidence:** `{f.snippet}`")
        lines.append(f"- **Why it matters:** {f.description}")
        note = result.triage_notes.get(f.fingerprint())
        if note and note.get("priority_rationale"):
            lines.append(f"- **Triage rationale:** {note['priority_rationale']}")
        fix = (note or {}).get("fix_guidance") or f.remediation
        lines.append(f"- **Fix:** {fix}")
        inv = result.investigations.get(f.fingerprint())
        if inv:
            # Render boundary: investigation strings are sanitized in the
            # loop already; sanitize again here so ANY investigation dict
            # reaching the renderer is markup-safe, whatever its origin.
            lines.append(
                f"- **Investigation:** {_md(inv['verdict'])} "
                f"({_md(inv['planner'])} planner, {inv['steps']} steps, {_md(inv['stopped_by'])})"
            )
            lines.append(f"  {_md(inv['summary'])}")
            for ev in inv["evidence"][:3]:
                srcs = ", ".join(_md(s) for s in ev["sources"][:3]) if ev["sources"] else "no locations"
                first_line = ev["note"].splitlines()[0] if ev["note"] else ""
                lines.append(f"  - {_md(first_line)} ({srcs})")
        lines.append("")
    lines.append("---")
    lines.append(
        "Generated by sentinel-triage. Findings come from conservative "
        "pattern rules and a small offline advisory set; treat them as a "
        "prioritized review queue, not proof of exploitability."
    )
    lines.append("")
    return "\n".join(lines)
